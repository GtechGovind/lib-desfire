/// @file
/// @brief Validated OpenSSL primitives shared by the DESFire authentication and messaging profiles.
/// Cipher padding and retained-IV policy belong to the protocol layer. Secret intermediate values
/// are erased locally; successful byte results transfer erasure responsibility to their caller.

#include "openssl_crypto.hpp"

#include "secret_buffer.hpp"

#include <algorithm>
#include <limits>

#include <openssl/crypto.h>
#include <openssl/evp.h>
#include <openssl/rand.h>
#if OPENSSL_VERSION_NUMBER >= 0x30000000L
#include <openssl/provider.h>
#endif

namespace desfire::detail {
  /// Keep provider and algorithm lookup isolated from application-wide OpenSSL configuration.
  struct crypto_context {
#if OPENSSL_VERSION_NUMBER >= 0x30000000L
    /// Private library context outlives both providers and every cipher operation using them.
    OSSL_LIB_CTX *library{nullptr};
    /// AES and modern DES variants are loaded from the default provider.
    OSSL_PROVIDER *default_provider{nullptr};
    /// Single DES requires the legacy provider on OpenSSL 3.
    OSSL_PROVIDER *legacy{nullptr};

    /// Release providers before destroying the context that owns them.
    ~crypto_context() {
      OSSL_PROVIDER_unload(legacy);
      OSSL_PROVIDER_unload(default_provider);
      OSSL_LIB_CTX_free(library);
    }
#endif
  };

  /// Own a fresh cipher-provider domain for one card, without changing global provider settings.
  /// OpenSSL 3 requires both default and legacy providers to support every advertised key type;
  /// partial setup releases its resources and returns crypto_error. OpenSSL 1.1.1 needs no setup.
  result<std::shared_ptr<crypto_context>> create_crypto_context() {
    auto context = std::make_shared<crypto_context>();
#if OPENSSL_VERSION_NUMBER >= 0x30000000L
    context->library = OSSL_LIB_CTX_new();
    if (!context->library) {
      return result<std::shared_ptr<crypto_context>>::failure({error_code::crypto_error});
    }

    context->default_provider = OSSL_PROVIDER_load(context->library, "default");
    context->legacy = OSSL_PROVIDER_load(context->library, "legacy");
    if (!context->default_provider || !context->legacy) {
      return result<std::shared_ptr<crypto_context>>::failure({error_code::crypto_error});
    }
#endif
    return result<std::shared_ptr<crypto_context>>::success(std::move(context));
  }

  /// Select the protocol block width after the caller has validated the key type.
  /// All supported DES variants use eight bytes and AES uses sixteen; invalid enums are not
  /// diagnosed here because key_size is the shared validity check at primitive boundaries.
  std::size_t block_size(key_type type) noexcept {
    return type == key_type::aes_128 ? 16 : 8;
  }

  /// Map a declared cipher to its exact raw-key byte count, excluding DESFire key-version metadata.
  /// Returning zero for unknown enums lets callers reject them before constructing an EVP cipher.
  std::size_t key_size(key_type type) noexcept {
    switch (type) {
    case key_type::des:
      return 8;
    case key_type::tdes_2k:
    case key_type::aes_128:
      return 16;
    case key_type::tdes_3k:
      return 24;
    }
    return 0;
  }

  /// Obtain an owned nonce from OpenSSL's cryptographic RNG; zero length succeeds without RNG work.
  /// Reject lengths outside RAND_bytes' signed-int domain and erase partially generated bytes on
  /// RNG failure. The receiver must erase successful nonce output after using it.
  result<bytes> generate_random_bytes(std::size_t size) {
    if (size > static_cast<std::size_t>(std::numeric_limits<int>::max())) {
      return result<bytes>::failure({error_code::invalid_argument});
    }

    bytes output(size);
    if (size && RAND_bytes(output.data(), static_cast<int>(size)) != 1) {
      secure_zero(output.data(), output.size());
      return result<bytes>::failure({error_code::crypto_error});
    }
    return result<bytes>::success(std::move(output));
  }

  namespace {
    /// Apply an EVP cipher to borrowed whole blocks, with no padding and no external IV mutation.
    /// Validate type, key/IV extents and the signed-int EVP bound before reading input; return
    /// invalid_argument for bad metadata or crypto_error for provider/operation failure. Erase
    /// partial output on crypto failure; successful owned output may contain secret plaintext.
    result<bytes> crypt(
      crypto_context &context,
      key_type type,
      byte_view key,
      byte_view iv,
      byte_view input,
      bool encrypt,
      bool use_cbc
    ) {
      if (
        key_size(type) == 0 || key.size() != key_size(type) ||
        (use_cbc && iv.size() != block_size(type)) || input.size() % block_size(type) ||
        input.size() > static_cast<std::size_t>(std::numeric_limits<int>::max()) - 16
      ) {
        return result<bytes>::failure({error_code::invalid_argument});
      }

      const char *cipher_name = nullptr;
      switch (type) {
      case key_type::des:
        cipher_name = use_cbc ? "DES-CBC" : "DES-ECB";
        break;
      case key_type::tdes_2k:
        cipher_name = use_cbc ? "DES-EDE-CBC" : "DES-EDE";
        break;
      case key_type::tdes_3k:
        cipher_name = use_cbc ? "DES-EDE3-CBC" : "DES-EDE3";
        break;
      case key_type::aes_128:
        cipher_name = use_cbc ? "AES-128-CBC" : "AES-128-ECB";
        break;
      }
#if OPENSSL_VERSION_NUMBER >= 0x30000000L
      std::unique_ptr<EVP_CIPHER, decltype(&EVP_CIPHER_free)> cipher(
        EVP_CIPHER_fetch(context.library, cipher_name, nullptr), EVP_CIPHER_free
      );
      const EVP_CIPHER *algorithm = cipher.get();
#else
      (void)context;
      const EVP_CIPHER *algorithm = EVP_get_cipherbyname(cipher_name);
#endif
      std::unique_ptr<EVP_CIPHER_CTX, decltype(&EVP_CIPHER_CTX_free)> operation(
        EVP_CIPHER_CTX_new(), EVP_CIPHER_CTX_free
      );
      if (
        !algorithm || !operation ||
        EVP_CipherInit_ex(
          operation.get(),
          algorithm,
          nullptr,
          key.data(),
          use_cbc ? iv.data() : nullptr,
          encrypt ? 1 : 0
        ) != 1 ||
        EVP_CIPHER_CTX_set_padding(operation.get(), 0) != 1
      ) {
        return result<bytes>::failure({error_code::crypto_error});
      }

      bytes output(input.size() + block_size(type));
      int written = 0;
      int final_size = 0;
      if (
        EVP_CipherUpdate(
          operation.get(), output.data(), &written, input.data(), static_cast<int>(input.size())
        ) != 1 ||
        EVP_CipherFinal_ex(operation.get(), output.data() + written, &final_size) != 1
      ) {
        secure_zero(output.data(), output.size());
        return result<bytes>::failure({error_code::crypto_error});
      }
      output.resize(static_cast<std::size_t>(written + final_size));
      return result<bytes>::success(std::move(output));
    }
  } // namespace

  /// Encrypt exactly one borrowed block as ECB, without retaining state or adding padding.
  /// Reject a wrong block extent locally; crypt validates the key/type and returns owned output
  /// or a precise argument/provider error. The caller owns any key-derived output it retains.
  result<bytes> encrypt_block(
    crypto_context &context,
    key_type type,
    byte_view key,
    byte_view input
  ) {
    if (input.size() != block_size(type)) {
      return result<bytes>::failure({error_code::invalid_argument});
    }
    return crypt(context, type, key, {}, input, true, false);
  }

  /// Decrypt one borrowed ECB block without padding; never mutate the caller's ciphertext/key.
  /// Wrong extents produce invalid_argument and EVP failures produce crypto_error. Successful
  /// plaintext is returned in ordinary owned bytes for the caller to consume and erase.
  result<bytes> decrypt_block(
    crypto_context &context,
    key_type type,
    byte_view key,
    byte_view input
  ) {
    if (input.size() != block_size(type)) {
      return result<bytes>::failure({error_code::invalid_argument});
    }
    return crypt(context, type, key, {}, input, false, false);
  }

  /// Encrypt whole borrowed blocks using the supplied full-width IV and return owned ciphertext.
  /// No padding or IV update occurs here: callers choose DESFire padding and retain the last
  /// ciphertext block only after success. Invalid metadata and EVP errors propagate from crypt.
  result<bytes> encrypt_cbc(
    crypto_context &context,
    key_type type,
    byte_view key,
    byte_view iv,
    byte_view input
  ) {
    return crypt(context, type, key, iv, input, true, true);
  }

  /// Decrypt whole borrowed blocks with a full-width IV, leaving every input unchanged.
  /// Return owned plaintext without stripping protocol checksums/padding; the caller verifies
  /// and erases it. Invalid metadata and EVP failures propagate without exposing partial output.
  result<bytes> decrypt_cbc(
    crypto_context &context,
    key_type type,
    byte_view key,
    byte_view iv,
    byte_view input
  ) {
    return crypt(context, type, key, iv, input, false, true);
  }

  /// Compare borrowed byte strings without content-dependent early exits for equal lengths.
  /// Extents are public protocol metadata, so a length mismatch fails immediately; empty ranges
  /// compare equal without passing potentially null pointers to CRYPTO_memcmp.
  bool constant_time_equal(
    byte_view left,
    byte_view right
  ) noexcept {
    return left.size() == right.size() &&
           (left.empty() || CRYPTO_memcmp(left.data(), right.data(), left.size()) == 0);
  }

  /// Compute an owned full-width CMAC for a borrowed message and static/session key.
  /// A missing IV means zero; a supplied full-width IV seeds DESFire's retained chaining state
  /// without mutating the input. Preserve the full tag for the profile's later truncation/IV
  /// update; erase subkeys and padded message storage, and propagate argument/provider errors.
  result<bytes> calculate_cmac(
    crypto_context &context,
    key_type type,
    byte_view key,
    byte_view input,
    byte_view initial_iv
  ) {
    const auto width = block_size(type);
    if (!initial_iv.empty() && initial_iv.size() != width) {
      return result<bytes>::failure({error_code::invalid_argument});
    }

    bytes zeros(width);
    auto encrypted_zero = encrypt_block(context, type, key, byte_view(zeros));
    if (!encrypted_zero) {
      return encrypted_zero;
    }
    secret_buffer encrypted_zero_block(std::move(encrypted_zero.value()));

    // CMAC doubles the encrypted zero block in GF(2^128) or GF(2^64); the reduction
    // polynomial is 0x87 for AES and 0x1b for the DES-family block width.
    /// Double one full-width secret block in the CMAC field and return an owned subkey.
    /// The caller supplies exactly width bytes and immediately adopts the output into erased
    /// storage; the reduction constant is selected by public cipher width, never key type width.
    auto double_subkey = [width](byte_view value) {
      bytes output(width);
      std::uint8_t carry = 0;
      for (std::size_t index = width; index > 0; --index) {
        output[index - 1] = static_cast<std::uint8_t>((value[index - 1] << 1) | carry);
        carry = static_cast<std::uint8_t>(value[index - 1] >> 7);
      }
      if (carry) {
        output.back() = static_cast<std::uint8_t>(output.back() ^ (width == 16 ? 0x87 : 0x1b));
      }
      return output;
    };
    secret_buffer subkey_1(double_subkey(encrypted_zero_block.view()));
    secret_buffer subkey_2(double_subkey(subkey_1.view()));
    // A complete final block uses K1; partial and empty messages use 0x80 padding and K2.
    const auto block_count = input.empty() ? 1 : (input.size() + width - 1) / width;
    secret_buffer block(bytes(block_count * width));
    if (!input.empty()) {
      std::copy(input.begin(), input.end(), block.data());
    }
    const bool complete_final_block = !input.empty() && input.size() % width == 0;
    if (!complete_final_block) {
      block.data()[input.size()] = 0x80;
    }
    const auto subkey = complete_final_block ? subkey_1.view() : subkey_2.view();
    for (std::size_t index = 0; index < width; ++index) {
      const auto offset = (block_count - 1) * width + index;
      block.data()[offset] = static_cast<std::uint8_t>(block.data()[offset] ^ subkey[index]);
    }
    auto encrypted = encrypt_cbc(
      context, type, key, initial_iv.empty() ? byte_view(zeros) : initial_iv, block.view()
    );
    if (!encrypted) {
      return encrypted;
    }
    secret_buffer ciphertext(std::move(encrypted.value()));
    return result<bytes>::success(
      bytes(ciphertext.data() + ciphertext.size() - width, ciphertext.data() + ciphertext.size())
    );
  }
} // namespace desfire::detail
